def plot_curves(data):
    fig, ax = plt.subplots(figsize=(8, 5))

    for key, values in data.items():
        x = [i / 10 for i in range(len(values))]   # index i  ->  x = i/10
        ax.plot(x, values, label=str(key), marker='o')

    ax.set_xlabel("x")
    ax.set_ylabel("y")
    ax.legend(title="Curve")
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.show()
    return fig, ax



